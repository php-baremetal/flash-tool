package build

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"phpflash/internal/config"
)

// EnvPair is one KEY=VALUE from a project's .env.
type EnvPair struct {
	Key   string
	Value string
}

var envKeyRe = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

// ParseDotEnv reads a simple .env: one KEY=VALUE per line, `#` starts a full-line comment, blank
// lines are ignored, an optional leading `export ` is dropped. The value is everything after the
// first `=` (trimmed); a matching pair of surrounding single or double quotes is stripped (double
// quotes also unescape \n \t \" \\). No shell expansion, no inline comments, no multiline. Invalid
// keys are skipped.
func ParseDotEnv(content string) []EnvPair {
	var pairs []EnvPair
	for _, raw := range strings.Split(content, "\n") {
		line := strings.TrimSpace(strings.TrimSuffix(raw, "\r"))
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if rest := strings.TrimPrefix(line, "export "); rest != line {
			line = strings.TrimSpace(rest)
		}
		eq := strings.IndexByte(line, '=')
		if eq <= 0 {
			continue
		}
		key := strings.TrimSpace(line[:eq])
		if !envKeyRe.MatchString(key) {
			continue
		}
		pairs = append(pairs, EnvPair{Key: key, Value: unquoteEnv(strings.TrimSpace(line[eq+1:]))})
	}
	return pairs
}

func unquoteEnv(v string) string {
	if len(v) >= 2 && v[0] == '"' && v[len(v)-1] == '"' {
		inner := v[1 : len(v)-1]
		inner = strings.ReplaceAll(inner, `\n`, "\n")
		inner = strings.ReplaceAll(inner, `\t`, "\t")
		inner = strings.ReplaceAll(inner, `\"`, `"`)
		inner = strings.ReplaceAll(inner, `\\`, `\`)
		return inner
	}
	if len(v) >= 2 && v[0] == '\'' && v[len(v)-1] == '\'' {
		return v[1 : len(v)-1]
	}
	return v
}

// cEscape renders a byte string as the body of a C string literal. Control bytes use octal escapes
// (fixed 3 digits, so they never merge with a following digit the way \x would).
func cEscape(s string) string {
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch c {
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			if c < 0x20 || c == 0x7f {
				fmt.Fprintf(&b, `\%03o`, c)
			} else {
				b.WriteByte(c)
			}
		}
	}
	return b.String()
}

// envSourceC renders the generated C table main.c applies with setenv(): a flat array of
// alternating key, value string literals plus the pair count.
func envSourceC(pairs []EnvPair) string {
	var b strings.Builder
	b.WriteString("/* Generated by phpflash from the project's .env -- do not edit. */\n")
	b.WriteString("const char *const php_esp32_env[] = {\n")
	for _, p := range pairs {
		fmt.Fprintf(&b, "    \"%s\", \"%s\",\n", cEscape(p.Key), cEscape(p.Value))
	}
	if len(pairs) == 0 {
		b.WriteString("    (const char *)0,\n") // dummy: never a zero-size array
	}
	b.WriteString("};\n")
	fmt.Fprintf(&b, "const int php_esp32_env_count = %d;\n", len(pairs))
	return b.String()
}

// EnvSourceArg bakes the project's .env into the firmware. When the [env] feature is on (the
// default, unless [env] enabled = false) and the env file exists, it parses the file and writes the
// generated C into buildDir, returning the -DPHP_ENV_SRC argument that adds it to the build. The
// bool is false when there is nothing to bake.
func EnvSourceArg(cfg *config.Config, projectDir, buildDir string) (string, bool, error) {
	if cfg.Env.Enabled != nil && !*cfg.Env.Enabled {
		return "", false, nil
	}
	file := cfg.Env.File
	if file == "" {
		file = ".env"
	}
	path := file
	if !filepath.IsAbs(path) {
		path = filepath.Join(projectDir, file)
	}
	content, err := os.ReadFile(path)
	if err != nil {
		return "", false, nil // no env file -> feature simply does nothing
	}
	if err := os.MkdirAll(buildDir, 0o755); err != nil {
		return "", false, err
	}
	pairs := ParseDotEnv(string(content))
	out := filepath.Join(buildDir, "php_env.gen.c")
	if err := os.WriteFile(out, []byte(envSourceC(pairs)), 0o644); err != nil {
		return "", false, err
	}
	return "-DPHP_ENV_SRC=" + out, true, nil
}
